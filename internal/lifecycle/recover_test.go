type recPlane struct {
	*cfgPlane
	order      []string
	recoverErr error
}

func (r *recPlane) RecoverPostgres(context.Context, *registry.Project, *secrets.ProjectKeys) error {
	r.order = append(r.order, "recover")
	return r.recoverErr
}

func (r *recPlane) ApplyPostgresSettings(ctx context.Context, p *registry.Project, k *secrets.ProjectKeys, restart bool, before func(context.Context)) (bool, error) {
	r.order = append(r.order, "apply")
	return r.cfgPlane.ApplyPostgresSettings(ctx, p, k, restart, before)
}

func TestApplyConfigRecoverStartsTheClusterBeforeApplying(t *testing.T) {
	h, cp, _, _ := configHarness(t)
	rp := &recPlane{cfgPlane: cp}
	h.e.plane = rp
	ctx := context.Background()
	p := h.create(t)

	if _, err := h.e.ApplyConfig(ctx, p.Ref, projectconfig.Postgres, ApplyOptions{RestartDatabase: true}); err != nil {
		t.Fatal(err)
	}
	if strings.Join(rp.order, ",") != "apply" {
		t.Fatalf("a plain apply must not recover: %v", rp.order)
	}
	rp.order = nil
	if _, err := h.e.ApplyConfig(ctx, p.Ref, projectconfig.Postgres, ApplyOptions{RestartDatabase: true, Recover: true}); err != nil {
		t.Fatal(err)
	}
	if strings.Join(rp.order, ",") != "recover,apply" || !cp.pgCalls[len(cp.pgCalls)-1] {
		t.Fatalf("order %v, restart flags %v", rp.order, cp.pgCalls)
	}
	// A cluster that cannot be brought back is an error, and the settings are not applied.
	rp.order = nil
	rp.recoverErr = errors.New("still down")
	if _, err := h.e.ApplyConfig(ctx, p.Ref, projectconfig.Postgres, ApplyOptions{Recover: true}); err == nil || !strings.Contains(err.Error(), "still down") {
		t.Fatalf("err = %v", err)
	}
	if strings.Join(rp.order, ",") != "recover" {
		t.Fatalf("order %v", rp.order)
	}
	// Recover is ignored by other services.
	rp.order = nil
	if _, err := h.e.ApplyConfig(ctx, p.Ref, projectconfig.Auth, ApplyOptions{Recover: true}); err != nil || len(rp.order) != 0 {
		t.Fatalf("auth with Recover: %v %v", err, rp.order)
	}
}

type checkPlane struct {
	*cfgPlane
	checked []projectconfig.Service
	err     error
}

func (c *checkPlane) CheckRender(_ context.Context, _ *registry.Project, _ *secrets.ProjectKeys, svc projectconfig.Service) error {
	c.checked = append(c.checked, svc)
	return c.err
}

// A paused project accepts settings that render; one that cannot be rendered fails the save,
// not the resume.
func TestApplyConfigOfAPausedProjectRendersWithoutStarting(t *testing.T) {
	h, cp, _, _ := configHarness(t)
	chk := &checkPlane{cfgPlane: cp}
	h.e.plane = chk
	ctx := context.Background()
	p := h.create(t)
	h.reg.SetProjectStatus(ctx, p.Ref, registry.StatusInactive)
	cp.services = nil

	res, err := h.e.ApplyConfig(ctx, p.Ref, projectconfig.Auth, ApplyOptions{})
	if err != nil || res.Applied || len(chk.checked) != 1 || chk.checked[0] != projectconfig.Auth || len(cp.services) != 0 {
		t.Fatalf("%+v %v checked=%v services=%v", res, err, chk.checked, cp.services)
	}
	chk.err = errors.New("GOTRUE_SMS_TEMPLATE contains a newline")
	if _, err := h.e.ApplyConfig(ctx, p.Ref, projectconfig.Auth, ApplyOptions{}); err == nil || !strings.Contains(err.Error(), "newline") {
		t.Fatalf("an unrenderable setting of a paused project must fail the save: %v", err)
	}
}

// Revoking a default key must not survive a key rotation: the rotated defaults are new keys.
func TestRotateKeysRevivesRevokedDefaultKeys(t *testing.T) {
	h := newHarness(t)
	ctx := context.Background()
	p := h.create(t)
	old, _ := h.e.Keys(ctx, p.Ref)
	for _, typ := range []string{secrets.KeyTypePublishable, secrets.KeyTypeSecret} {
		rec := secrets.APIKeyRecord{ID: secrets.KeyID(p.Ref, secrets.DefaultKeyName, typ), Name: secrets.DefaultKeyName, Type: typ, Default: true, Revoked: true}
		b, _ := secrets.MarshalRecord(rec)
		sealed, _ := h.sec.Seal(b)
		if err := h.reg.PutSecret(ctx, p.Ref, secrets.RecordSecretName(rec.ID), sealed); err != nil {
			t.Fatal(err)
		}
	}
	if k, _ := h.e.Keys(ctx, p.Ref); len(k.OpaqueKeys(p.Ref)) != 0 {
		t.Fatalf("both default keys should be revoked: %v", k.OpaqueKeys(p.Ref))
	}
	nk, err := h.e.RotateKeys(ctx, p.Ref)
	if err != nil {
		t.Fatal(err)
	}
	stored, _ := h.e.Keys(ctx, p.Ref)
	got := stored.OpaqueKeys(p.Ref)
	if len(got) != 2 || nk.SecretKey == old.SecretKey {
		t.Fatalf("the rotated default keys must be active: %v", got)
	}
	found := map[string]bool{}
	for _, k := range got {
		found[k.Key] = true
	}
	if !found[nk.SecretKey] || !found[nk.PublishableKey] {
		t.Fatalf("active keys are not the rotated ones: %v", got)
	}
}
