func TestStripManagedSettings(t *testing.T) {
	body := "# Do not edit this file manually!\n" +
		"max_locks_per_transaction = '2147483640'\n" +
		"  Statement_Timeout = '5s'\n" +
		"cron.log_statement = 'off'\n" +
		"unmanaged_extension.setting = 'x'\n" +
		"work_mem = '8MB'\n"
	got, changed := stripManagedSettings(body)
	if !changed || got != "# Do not edit this file manually!\nunmanaged_extension.setting = 'x'\n" {
		t.Fatalf("changed=%v body=%q", changed, got)
	}
	if again, changed := stripManagedSettings(got); changed || again != got {
		t.Fatalf("a clean file must stay as it is: %q", again)
	}
}

// fakeSup records what the plane does to the units; a postgres unit that was told to start
// reports failed, like one that cannot start on its settings.
type fakeSup struct {
	mu     sync.Mutex
	log    []string
	failed bool
}

func (f *fakeSup) rec(s string) { f.mu.Lock(); f.log = append(f.log, s); f.mu.Unlock() }
func (f *fakeSup) Render(_ context.Context, s units.Spec) error {
	f.rec("render " + s.Unit())
	return nil
}
func (f *fakeSup) Start(_ context.Context, u string) error { f.rec("start " + u); return nil }
func (f *fakeSup) Stop(_ context.Context, u string) error  { f.rec("stop " + u); return nil }
func (f *fakeSup) Status(context.Context, string) (units.Status, error) {
	return units.Status{State: units.StateFailed}, nil
}
func (f *fakeSup) Remove(context.Context, string) error { return nil }

func (f *fakeSup) index(s string) int {
	f.mu.Lock()
	defer f.mu.Unlock()
	for i, l := range f.log {
		if l == s {
			return i
		}
	}
	return -1
}

// A cluster that cannot start on a setting Postgres accepted in ALTER SYSTEM must be started
// again on the saved settings: the project stops, the managed lines leave postgresql.auto.conf
// offline, and the cluster unit starts (its wait then fails here only because there is no
// real Postgres behind the fake).
func TestRecoverPostgresClearsAutoConfAndStartsTheCluster(t *testing.T) {
	cfg := config.Default()
	cfg.StateDir = shortTempDir(t)
	cfg.Domain = "example.test"
	cfg.BinPath = "/usr/local/bin/sbctl"
	sup := &fakeSup{}
	pl := NewPostgresPlane(cfg, sup, fakeArts{}, registry.NewMemory(), PlaneOptions{})
	p := testProject(cfg, "abcdefghijklmnopqrst", 2)
	keys := testKeys(t, p.Ref)
	pp := pl.paths(p)
	if err := os.MkdirAll(pp.Data, 0o700); err != nil {
		t.Fatal(err)
	}
	auto := filepath.Join(pp.Data, "postgresql.auto.conf")
	if err := os.WriteFile(auto, []byte("# managed by ALTER SYSTEM\nmax_locks_per_transaction = '2147483640'\nlog_connections = 'on'\nextension.keep = 'yes'\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	err := pl.RecoverPostgres(context.Background(), p, keys)
	if err == nil {
		t.Fatal("the fake cluster never answers; the start must report it")
	}
	b, _ := os.ReadFile(auto)
	if strings.Contains(string(b), "max_locks_per_transaction") || strings.Contains(string(b), "log_connections") || !strings.Contains(string(b), "extension.keep") {
		t.Fatalf("auto.conf after recovery:\n%s", b)
	}
	pg := config.UnitName(config.SvcPostgres, p.Ref)
	stop, start := sup.index("stop "+pg), sup.index("start "+pg)
	if stop < 0 || start < 0 || start < stop {
		t.Fatalf("the cluster must stop, then start again: %v", sup.log)
	}
	// The cluster starts from rendered files, so the saved settings are in its unit.
	if sup.index("render "+pg) < 0 {
		t.Fatalf("the unit was not rendered: %v", sup.log)
	}
}

